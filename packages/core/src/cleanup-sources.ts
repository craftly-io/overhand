const BY_ID = new Map(SOURCES.map((s) => [s.id, s]));

/** One source by id; a typo fails at once rather than proposing nothing. */
export function source(id: string): Source {
  const s = BY_ID.get(id);
  if (!s) throw new Error(`no cleanup source ${id}`);
  return s;
}

/** A source's paths on this OS (macOS or Linux). */
export const pathsOn = (s: Source, platform: string): string[] => [
  ...(s.paths ?? []),
  ...((platform === "darwin" ? s.mac : s.linux) ?? []),
];

/** The tools' own cleanup commands, the config's default `caches.commands`. */
export const sourceCommands = (): string[] => SOURCES.filter((s) => s.category === "caches" && s.cmd).map((s) => s.cmd ?? "");

/** Folder names inside projects that the builds category may remove, the config's default `builds.dirs`. */
export const buildDirs = (): string[] => SOURCES.filter((s) => s.category === "builds").flatMap((s) => s.dirs ?? []);

const SAFE: Record<Source["type"], string> = {
  cache: "yes; unattended only when its tool isn't running and it's a day old",
  record: "only when you confirm it; never unattended",
  download: "yes, by hand; never unattended",
  rule: "when its own checks pass",
};

/** docs/cleanup-sources.md: the table people read, printed from SOURCES. */
export function sourcesTable(): string {
  const cell = (xs: string[] | undefined) => (xs?.length ? xs.map((x) => `\`${x}\``).join("<br>") : "—");
  const rows = SOURCES.map((s) => {
    const both = [...(s.paths ?? []), ...(s.dirs ?? []), ...Object.values(s.packages ?? {}).flatMap((p) => p.config)];
    return [
      s.id,
      s.tool,
      cell([...both, ...(s.mac ?? [])]),
      cell([...both, ...(s.linux ?? [])]),
      s.what + (s.days ? ` (offered after ${s.days} days unused)` : ""),
      SAFE[s.type],
      s.back,
      `[docs](${s.ref})`,
    ].join(" | ");
  });
  return [
    "# Where Cleanup looks",
    "",
    "Printed from `packages/core/src/cleanup-sources.ts` by `bun packages/core/src/cleanup-sources.ts`; a test fails when they differ. Nothing outside these rows is ever removed.",
    "",
    "| id | tool | macOS | Linux | what it is | safe to remove | comes back | source |",
    "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ...rows.map((r) => `| ${r} |`),
    "",
  ].join("\n");
}

// env.ts loads config.ts, which imports this file: read SRC only when run as a script
if (import.meta.main) void import("./env").then(({ SRC }) => writeFileSync(join(SRC, "docs", "cleanup-sources.md"), sourcesTable()));
