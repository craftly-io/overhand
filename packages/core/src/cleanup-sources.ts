/**
 * Where the tools people build with agents keep their downloads, caches and history: the one list cleanup's rules read.
 * docs/cleanup-sources.md is printed from it (`bun packages/core/src/cleanup-sources.ts`), and a test fails when the two differ, so every
 * rule has its cited row and every row a rule. Paths: `~/` is the home folder, `$TMPDIR/` the temp folder, a trailing
 * `*` matches every entry that starts so, and a bare name (`dirs`) is a folder inside a project.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import type { CleanupCategory } from "@overhand/contract";

export interface Source {
  id: string;
  tool: string;
  category: CleanupCategory;
  /** What it is, in a few words. */
  what: string;
  /**
   * cache: rebuilds itself (unattended only when its tool isn't running and it's a day old); record: your own history,
   * never unattended, offered by age; download: comes back by a download or a reinstall, never unattended; rule: a
   * scanner of its own decides (git, a tool's command).
   */
  type: "cache" | "record" | "download" | "rule";
  /** How it comes back, or what's lost for good. */
  back: string;
  /** Under both macOS and Linux, and each OS's own. */
  paths?: string[];
  mac?: string[];
  linux?: string[];
  /** Folder names inside projects (dependencies and build output). */
  dirs?: string[];
  /** Every entry inside is its own item, offered once unused `days`. */
  each?: boolean;
  /** Only entries older than the newest version of the same name (`chromium-1187` beside `chromium-1243`). */
  old?: boolean;
  /** Days unused before it's offered (records and downloads); caches: 1. */
  days?: number;
  /** It shares files (hard links, clones) with what it made, so what removing it frees can't be measured beforehand. */
  shared?: boolean;
  /** Program names (argv[0]) and macOS app bundles that use it: while one runs, nothing here goes unattended. */
  procs?: string[];
  apps?: string[];
  /** Its tool's own command (the config's caches commands start from these). */
  cmd?: string;
  /** For agent versions: links that point at the version in use. */
  links?: string[];
  /** For agent CLIs, by runtime id: the package each package manager installs, and the CLI's own config folders. */
  packages?: Record<string, { npm?: string; uv?: string; brew?: string; cask?: string; config: string[] }>;
  /** Where this is documented. */
  ref: string;
}

