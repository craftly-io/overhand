/**
 * The only words a world may reword: the greeting on Now, the story lines it tells when nothing is happening, a few
 * empty-state lines. Everything else (navigation, view names, actions, labels, statuses, counts,
 * kickers, toasts, settings, errors, the command bar, the night report) is plain English in every world.
 */
export const FLAVOUR_KEYS = [
  "brHelloNight",
  "brHelloMorning",
  "brHelloAfternoon",
  "brHelloEvening",
  "brCalm",
  "brIdle",
  "calm",
  "emptyMine",
  "emptyActivity",
] as const satisfies readonly WordKey[];

/** A label the dashboard shows. */
export type WordKey = keyof typeof plainWords;

/** A theme's full vocabulary: every key, no extras. Leaving one out is a type error. */
export type Words = { readonly [K in WordKey]: string };

/** The `{placeholders}` a word uses, sorted, so a theme can be checked against plain English. */
export function placeholders(word: string): string[] {
  return [...word.matchAll(/\{(\w+)\}/g)].map((m) => m[1] ?? "").sort();
}
