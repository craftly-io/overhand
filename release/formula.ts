/**
 * Writes the Homebrew formula for a release from its SHA256SUMS, so `brew install craftly-io/tap/overhand` gets the same
 * package as the installer, checked against the same sums. launch.ts pushes it to craftly-io/homebrew-tap.
 * Usage: bun release/formula.ts <version> <SHA256SUMS file>   (prints the formula)
 */
import { readFileSync } from "node:fs";
import { DOWNLOAD, SITE } from "../packages/contract/src/links";

/** The formula for `version` (no leading v), its URLs and sha256s taken from the release's SHA256SUMS text. */
export function formula(version: string, sums: string): string {
  const sha = (os: string, arch: string): string => {
    const name = `overhand-${os}-${arch}.tar.gz`;
    const hit = sums.match(new RegExp(`^([0-9a-f]{64})  ${name.replaceAll(".", "\\.")}$`, "m"))?.[1];
    if (!hit) throw new Error(`SHA256SUMS has no ${name}`);
    return hit;
  };
  const pkg = (os: string, arch: string, indent: string): string =>
    [`${indent}url "${DOWNLOAD}/v${version}/overhand-${os}-${arch}.tar.gz"`, `${indent}sha256 "${sha(os, arch)}"`].join("\n");
  return `# Generated by release/formula.ts from the v${version} release's SHA256SUMS; don't edit by hand.
class Overhand < Formula
  desc "Stop babysitting your coding agents"
  homepage "${SITE}"
  license "FSL-1.1-ALv2"
  version "${version}"

  on_macos do
    on_arm do
${pkg("darwin", "arm64", "      ")}
    end
    on_intel do
${pkg("darwin", "x64", "      ")}
    end
  end

  on_linux do
    on_arm do
${pkg("linux", "arm64", "      ")}
    end
    on_intel do
${pkg("linux", "x64", "      ")}
    end
  end

  def install
    # the binary serves the dashboard from web/ beside it, so both stay together; on a Mac its menu bar helper too
    libexec.install "overhand", "web"
    libexec.install "overhand-menubar" if File.exist?("overhand-menubar")
    bin.install_symlink libexec/"overhand"
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/overhand version").strip
  end
end
`;
}

if (import.meta.main) {
  const [version, file] = process.argv.slice(2);
  if (!version || !file) throw new Error("usage: bun release/formula.ts <version> <SHA256SUMS file>");
  process.stdout.write(formula(version.replace(/^v/, ""), readFileSync(file, "utf8")));
}
